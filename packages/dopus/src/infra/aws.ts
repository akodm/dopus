import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { detectProject } from '../init/detect.js'
import { APPROVAL_SECRET_ENV, type InitIO, installArgs } from '../init/run.js'
import { PROVIDERS, type ProviderInfo } from '../providers.js'

export interface InfraOptions {
  cwd: string
  yes?: boolean
  install?: boolean
}

export type InfraIO = Pick<InitIO, 'confirm' | 'info' | 'warn' | 'success' | 'install'> & {
  note(message: string, title: string): void
}

export interface InfraAwsResult {
  configFile: string
  created: boolean
  /** The existing config already enables streaming. */
  streaming: boolean
  provider: ProviderInfo | undefined
  installed: string[]
}

export const OPEN_NEXT_CONFIG = `import type { OpenNextConfig } from '@opennextjs/aws/types/open-next.js'

/**
 * Generated by \`dopus infra aws\`.
 *
 * Lambda response streaming lets /api/agent stream replies instead of buffering them. OpenNext marks the
 * server as streaming in its build output; SST (sst.aws.Nextjs) reads that and sets the Function URL
 * invoke mode to RESPONSE_STREAM. With your own CDK/Terraform, set InvokeMode RESPONSE_STREAM yourself.
 */
const config = {
  default: {
    override: {
      wrapper: 'aws-lambda-streaming',
    },
  },
} satisfies OpenNextConfig

export default config
`

/** Which provider agent.config.ts uses, so the deploy snippet names the right env var. */
export function detectConfiguredProvider(source: string | undefined) {
  if (!source) return undefined
  return Object.values(PROVIDERS).find((info) => source.includes(`'${info.packageName}'`))
}

function secretName(envVar: string) {
  return envVar
    .toLowerCase()
    .split('_')
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join('')
}

export function sstSnippet(provider: ProviderInfo | undefined) {
  const keyEnv = provider?.envVar ?? 'OPENAI_API_KEY'
  const keySecret = secretName(keyEnv)
  const approval = secretName(APPROVAL_SECRET_ENV)
  return `// sst.config.ts → run()
const ${keySecret[0]?.toLowerCase()}${keySecret.slice(1)} = new sst.Secret('${keySecret}')
const ${approval[0]?.toLowerCase()}${approval.slice(1)} = new sst.Secret('${approval}')

new sst.aws.Nextjs('Web', {
  server: {
    // Lambda timeout; SST also uses it as the CloudFront read
    // timeout (max 60 s, or up to 180 s with a quota increase).
    timeout: '60 seconds',
  },
  environment: {
    ${keyEnv}: ${keySecret[0]?.toLowerCase()}${keySecret.slice(1)}.value,
    ${APPROVAL_SECRET_ENV}: ${approval[0]?.toLowerCase()}${approval.slice(1)}.value,
  },
})

// then, once per stage:
//   npx sst secret set ${keySecret} <your key>
//   npx sst secret set ${approval} "$(openssl rand -base64 32)"`
}

export async function runInfraAws(options: InfraOptions, io: InfraIO): Promise<InfraAwsResult> {
  const project = detectProject(options.cwd)
  const { root } = project
  const ask = async (message: string, initial: boolean) =>
    options.yes ? initial : io.confirm(message, initial)

  const configFile = ['open-next.config.ts', 'open-next.config.js', 'open-next.config.mjs'].find(
    (f) => existsSync(join(root, f)),
  )
  const agentConfig = [join(project.configDir, 'agent.config.ts'), 'agent.config.ts']
    .map((f) => join(root, f))
    .find((f) => existsSync(f))
  const provider = detectConfiguredProvider(
    agentConfig ? readFileSync(agentConfig, 'utf8') : undefined,
  )

  const result: InfraAwsResult = {
    configFile: configFile ?? 'open-next.config.ts',
    created: false,
    streaming: false,
    provider,
    installed: [],
  }

  if (configFile) {
    result.streaming = readFileSync(join(root, configFile), 'utf8').includes('aws-lambda-streaming')
    if (result.streaming) {
      io.info(`${configFile} already enables Lambda streaming — left unchanged.`)
    } else {
      io.warn(
        `${configFile} exists and does not enable streaming. Add \`override: { wrapper: 'aws-lambda-streaming' }\` ` +
          'to the function that serves /api/agent (or to `default`).',
      )
    }
  } else {
    writeFileSync(join(root, 'open-next.config.ts'), OPEN_NEXT_CONFIG)
    result.created = true
    result.streaming = true
    io.success('Created open-next.config.ts (Lambda response streaming)')
  }

  if (!project.dependencies['@opennextjs/aws']) {
    const spec = '@opennextjs/aws@^4'
    if (options.install === false) {
      io.warn(
        `Install it yourself: ${project.packageManager} ${installArgs(project.packageManager, [spec], true).join(' ')}`,
      )
    } else if (
      await ask(`Install ${spec} (dev dependency) with ${project.packageManager}?`, true)
    ) {
      await io.install(project.packageManager, [spec], root, true)
      result.installed = [spec]
    }
  }

  if (!provider)
    io.warn('Could not tell the provider from agent.config.ts; the snippet below assumes OpenAI.')
  io.note(sstSnippet(provider), 'Deploy with SST')
  io.note(
    [
      'Build: npx @opennextjs/aws build (SST runs it for you).',
      'Keep-alive: dopus sends an SSE comment every 15 s while a tool',
      '  runs. CloudFront times out on gaps between packets, not on',
      '  total time, so long tool calls keep the stream open.',
      'Limit: a turn must finish within the Lambda timeout: 60 s',
      '  behind CloudFront by default, up to 15 min on a bare',
      '  Function URL.',
      'Avoid API Gateway HTTP APIs for /api/agent (30 s cap).',
    ].join('\n'),
    'AWS notes',
  )
  return result
}
