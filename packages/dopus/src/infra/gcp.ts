import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { detectProject, InitError, type PackageManager } from '../init/detect.js'
import { APPROVAL_SECRET_ENV } from '../init/run.js'
import { detectConfiguredProvider, type InfraIO, type InfraOptions } from './aws.js'
import { workerName } from './cloudflare.js'

export interface InfraGcpResult {
  created: string[]
  skipped: string[]
  /** `output: 'standalone'` is set in next.config (now or before). */
  standalone: boolean
}

const LOCKFILE: Record<Exclude<PackageManager, 'bun'>, string> = {
  pnpm: 'pnpm-lock.yaml',
  npm: 'package-lock.json',
  yarn: 'yarn.lock',
}

/**
 * The install line. pnpm/yarn come from corepack; without a `packageManager` field corepack would fetch the
 * newest release, whose policies (e.g. pnpm's minimumReleaseAge) can reject a lockfile your version accepted,
 * so pin the version the project uses.
 */
function installCommand(
  packageManager: Exclude<PackageManager, 'bun'>,
  pinned: string | undefined,
) {
  if (packageManager === 'npm') return 'npm ci'
  const activate = pinned
    ? `corepack enable ${packageManager} && corepack prepare ${packageManager}@${pinned} --activate`
    : `corepack enable ${packageManager}`
  return `${activate} && ${packageManager} install --frozen-lockfile`
}

/** Version to pin when package.json has no `packageManager` field: the one installed here. */
export function localVersion(packageManager: PackageManager, cwd: string): string | undefined {
  try {
    const version = execFileSync(packageManager, ['--version'], {
      cwd,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim()
    return /^\d+\.\d+\.\d+/.test(version) ? version : undefined
  } catch {
    return undefined
  }
}

/** `pin`: version to activate with corepack; leave undefined when package.json declares `packageManager`. */
export function dockerfile(packageManager: PackageManager, pin?: string) {
  if (packageManager === 'bun') {
    throw new InitError(
      'Bun projects: write your own Dockerfile (dopus generates npm, pnpm and yarn ones).',
    )
  }
  const lockfile = LOCKFILE[packageManager]
  const install = installCommand(packageManager, pin)
  return `# Generated by \`dopus infra gcp\`: Next.js standalone server for Cloud Run.
# Secrets are not baked in: .dockerignore excludes .env files; Cloud Run injects them at runtime.
FROM node:24-slim AS base
ENV NEXT_TELEMETRY_DISABLED=1

FROM base AS deps
WORKDIR /app
COPY package.json ${lockfile} ./
RUN ${install}

FROM base AS build
WORKDIR /app
COPY --from=deps /app/node_modules ./node_modules
COPY . .
RUN node_modules/.bin/next build && mkdir -p public

FROM base AS run
WORKDIR /app
ENV NODE_ENV=production PORT=8080 HOSTNAME=0.0.0.0
RUN groupadd --system --gid 1001 nodejs && useradd --system --uid 1001 --gid nodejs nextjs
COPY --from=build --chown=nextjs:nodejs /app/.next/standalone ./
COPY --from=build --chown=nextjs:nodejs /app/.next/static ./.next/static
COPY --from=build --chown=nextjs:nodejs /app/public ./public
USER nextjs
EXPOSE 8080
CMD ["node", "server.js"]
`
}

export const DOCKERIGNORE = `# Generated by \`dopus infra gcp\`. Keep secrets and build output out of the image.
node_modules
.next
.open-next
.wrangler
.git
.env
.env.*
.dev.vars*
npm-debug.log*
Dockerfile
.dockerignore
`

const STANDALONE = /output\s*:\s*['"]standalone['"]/

/**
 * Adds `output: 'standalone'` to the usual `const nextConfig = {…}` / `export default {…}` shapes.
 * Returns undefined when the file does not match a shape it can edit safely.
 */
export function addStandalone(source: string): string | undefined {
  if (STANDALONE.test(source)) return source
  if (/\boutput\s*:/.test(source)) return undefined
  const patterns = [
    /(const\s+nextConfig(?:\s*:\s*NextConfig)?\s*=\s*)\{\s*\}/,
    /(const\s+nextConfig(?:\s*:\s*NextConfig)?\s*=\s*)\{/,
    /(export\s+default\s*)\{\s*\}/,
    /(module\.exports\s*=\s*)\{\s*\}/,
  ]
  for (const pattern of patterns) {
    if (!pattern.test(source)) continue
    return source.replace(pattern, (match, head: string) =>
      match.trimEnd().endsWith('}')
        ? `${head}{\n  output: 'standalone',\n}`
        : `${head}{\n  output: 'standalone',`,
    )
  }
  return undefined
}

function secretId(envVar: string) {
  return envVar.toLowerCase().replaceAll('_', '-')
}

export async function runInfraGcp(options: InfraOptions, io: InfraIO): Promise<InfraGcpResult> {
  const project = detectProject(options.cwd)
  const { root } = project
  const ask = async (message: string, initial: boolean) =>
    options.yes ? initial : io.confirm(message, initial)
  const result: InfraGcpResult = { created: [], skipped: [], standalone: false }

  const nextConfig = ['next.config.ts', 'next.config.mjs', 'next.config.js'].find((f) =>
    existsSync(join(root, f)),
  )
  if (!nextConfig) {
    writeFileSync(
      join(root, 'next.config.mjs'),
      "/** @type {import('next').NextConfig} */\nexport default { output: 'standalone' }\n",
    )
    result.created.push('next.config.mjs')
    result.standalone = true
    io.success("Created next.config.mjs with output: 'standalone'")
  } else {
    const source = readFileSync(join(root, nextConfig), 'utf8')
    const patched = addStandalone(source)
    if (patched === source) {
      result.standalone = true
    } else if (
      patched &&
      (await ask(`Set output: 'standalone' in ${nextConfig}? (needed for the container)`, true))
    ) {
      writeFileSync(join(root, nextConfig), patched)
      result.standalone = true
      io.success(`${nextConfig}: set output: 'standalone'`)
    } else {
      io.warn(
        `Set \`output: 'standalone'\` in ${nextConfig} yourself; the Dockerfile copies .next/standalone.`,
      )
    }
  }

  const files: [string, () => string][] = [
    [
      'Dockerfile',
      () => {
        const declared = (
          JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')) as {
            packageManager?: string
          }
        ).packageManager
        return dockerfile(
          project.packageManager,
          declared ? undefined : localVersion(project.packageManager, root),
        )
      },
    ],
    ['.dockerignore', () => DOCKERIGNORE],
  ]
  for (const [file, content] of files) {
    if (existsSync(join(root, file))) {
      result.skipped.push(file)
      io.info(`${file} exists — left unchanged.`)
      continue
    }
    writeFileSync(join(root, file), content())
    result.created.push(file)
    io.success(`Created ${file}`)
  }
  if (result.skipped.includes('.dockerignore')) {
    const ignore = readFileSync(join(root, '.dockerignore'), 'utf8')
    if (!/^\.env/m.test(ignore))
      io.warn('.dockerignore does not exclude .env files: your secrets would end up in the image.')
  }

  const agentConfig = [join(project.configDir, 'agent.config.ts'), 'agent.config.ts']
    .map((f) => join(root, f))
    .find((f) => existsSync(f))
  const provider = detectConfiguredProvider(
    agentConfig ? readFileSync(agentConfig, 'utf8') : undefined,
  )
  const keyEnv = provider?.envVar ?? 'OPENAI_API_KEY'
  const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')) as { name?: string }
  const service = workerName(pkg.name)
  io.note(
    [
      'Secrets (Secret Manager), once per project:',
      `  printf %s "$KEY" | gcloud secrets create ${secretId(keyEnv)} --data-file=-`,
      `  openssl rand -base64 32 | tr -d '\\n' | gcloud secrets create ${secretId(APPROVAL_SECRET_ENV)} --data-file=-`,
      '  (the Cloud Run service account needs roles/secretmanager.secretAccessor)',
      '',
      'Deploy (Cloud Build uses the Dockerfile):',
      `  gcloud run deploy ${service} --source . --region <region> --timeout 3600 \\`,
      `    --set-secrets ${keyEnv}=${secretId(keyEnv)}:latest,${APPROVAL_SECRET_ENV}=${secretId(APPROVAL_SECRET_ENV)}:latest`,
      '',
      'Local check:',
      `  docker build -t ${service} . && docker run --rm -p 8080:8080 --env-file .env.local ${service}`,
    ].join('\n'),
    'Deploy to Cloud Run',
  )
  io.note(
    [
      'Timeout: a request (the whole streamed reply) may last up to 60 min',
      '  (--timeout 3600; default 5 min). For longer work use Cloud Run Jobs',
      '  and pass the user explicitly (identify → ctx.user): no cookies there.',
      'Instances are billed while a stream is open; keep-alive comments (15 s)',
      '  keep load balancers and proxies from dropping long tool calls.',
    ].join('\n'),
    'Cloud Run notes',
  )
  return result
}
