import { appendFileSync, existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { detectProject, InitError } from '../init/detect.js'
import { isGitIgnored, parseEnvKeys, upsertEnv } from '../init/env.js'
import { APPROVAL_SECRET_ENV, installArgs } from '../init/run.js'
import { detectConfiguredProvider, type InfraIO, type InfraOptions } from './aws.js'

export interface InfraCloudflareResult {
  created: string[]
  skipped: string[]
  scripts: string[]
  installed: string[]
}

export const CLOUDFLARE_OPEN_NEXT_CONFIG = `import { defineCloudflareConfig } from '@opennextjs/cloudflare'

// Generated by \`dopus infra cloudflare\`. Add an incremental cache (R2/KV) here if your pages use ISR.
export default defineCloudflareConfig({})
`

/** Worker names: lowercase letters, digits and dashes, at most 63 characters. */
export function workerName(packageName: string | undefined) {
  const name = (packageName ?? 'next-app')
    .replace(/^@[^/]+\//, '')
    .toLowerCase()
    .replace(/[^a-z0-9-]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 63)
  return name || 'next-app'
}

/** A month back, so the installed workerd always supports it. */
export function compatibilityDate(now = new Date()) {
  return new Date(now.getTime() - 30 * 24 * 3600 * 1000).toISOString().slice(0, 10)
}

export function wranglerConfig(name: string, date: string) {
  return `{
  // Generated by \`dopus infra cloudflare\` for @opennextjs/cloudflare.
  "$schema": "node_modules/wrangler/config-schema.json",
  "name": "${name}",
  "main": ".open-next/worker.js",
  "compatibility_date": "${date}",
  "compatibility_flags": ["nodejs_compat", "global_fetch_strictly_public"],
  "assets": { "directory": ".open-next/assets", "binding": "ASSETS" },
  "services": [{ "binding": "WORKER_SELF_REFERENCE", "service": "${name}" }],
  // Waiting on the LLM does not count as CPU time, but rendering and tool code do (paid plans: 30 s default).
  // "limits": { "cpu_ms": 60000 },
  "observability": { "enabled": true }
}
`
}

const SCRIPTS: Record<string, string> = {
  'cf:preview': 'opennextjs-cloudflare build && opennextjs-cloudflare preview',
  'cf:deploy': 'opennextjs-cloudflare build && opennextjs-cloudflare deploy',
}

export async function runInfraCloudflare(
  options: InfraOptions,
  io: InfraIO,
): Promise<InfraCloudflareResult> {
  const project = detectProject(options.cwd)
  const { root } = project
  const ask = async (message: string, initial: boolean) =>
    options.yes ? initial : io.confirm(message, initial)
  const result: InfraCloudflareResult = { created: [], skipped: [], scripts: [], installed: [] }

  const openNext = ['open-next.config.ts', 'open-next.config.js', 'open-next.config.mjs'].find(
    (f) => existsSync(join(root, f)),
  )
  if (openNext && !readFileSync(join(root, openNext), 'utf8').includes('@opennextjs/cloudflare')) {
    throw new InitError(
      `${openNext} is set up for another target (AWS?). OpenNext uses one config per app: move it away and rerun.`,
    )
  }

  const pkgPath = join(root, 'package.json')
  const pkgSource = readFileSync(pkgPath, 'utf8')
  const pkg = JSON.parse(pkgSource) as { name?: string; scripts?: Record<string, string> }
  const name = workerName(pkg.name)

  const agentConfig = [join(project.configDir, 'agent.config.ts'), 'agent.config.ts']
    .map((f) => join(root, f))
    .find((f) => existsSync(f))
  const provider = detectConfiguredProvider(
    agentConfig ? readFileSync(agentConfig, 'utf8') : undefined,
  )
  const keyEnv = provider?.envVar ?? 'OPENAI_API_KEY'

  const files: [string, string, string[]][] = [
    [
      'open-next.config.ts',
      CLOUDFLARE_OPEN_NEXT_CONFIG,
      ['open-next.config.js', 'open-next.config.mjs'],
    ],
    [
      'wrangler.jsonc',
      wranglerConfig(name, compatibilityDate()),
      ['wrangler.json', 'wrangler.toml'],
    ],
    ['.dev.vars', 'NEXTJS_ENV=development\n', []],
  ]
  for (const [file, content, alternatives] of files) {
    const existing = [file, ...alternatives].find((f) => existsSync(join(root, f)))
    if (existing) {
      result.skipped.push(existing)
      io.info(`${existing} exists — left unchanged.`)
      continue
    }
    writeFileSync(join(root, file), content, file === '.dev.vars' ? { mode: 0o600 } : undefined)
    result.created.push(file)
    io.success(`Created ${file}`)
  }
  // Wrangler reads .dev.vars and then ignores .env files, so the local preview needs the secrets there too.
  const envLocal = join(root, '.env.local')
  const devVars = join(root, '.dev.vars')
  const local = existsSync(envLocal)
    ? parseEnvKeys(readFileSync(envLocal, 'utf8'))
    : new Map<string, string>()
  const present = existsSync(devVars)
    ? parseEnvKeys(readFileSync(devVars, 'utf8'))
    : new Map<string, string>()
  const copy = [keyEnv, APPROVAL_SECRET_ENV].filter((key) => local.get(key) && !present.get(key))
  if (
    copy.length > 0 &&
    (await ask(
      `Copy ${copy.join(' and ')} from .env.local into .dev.vars for the local preview?`,
      true,
    ))
  ) {
    const vars = Object.fromEntries(copy.map((key) => [key, local.get(key) ?? '']))
    writeFileSync(devVars, upsertEnv(readFileSync(devVars, 'utf8'), vars).content, { mode: 0o600 })
    io.success(`.dev.vars: set ${copy.join(', ')}`)
  }

  if (result.skipped.some((f) => f.startsWith('wrangler.'))) {
    io.warn(
      'Check that your wrangler config has main ".open-next/worker.js" and the "nodejs_compat" flag.',
    )
  }

  const scripts = { ...pkg.scripts }
  for (const [key, command] of Object.entries(SCRIPTS)) {
    if (!scripts[key]) {
      scripts[key] = command
      result.scripts.push(key)
    }
  }
  if (result.scripts.length > 0) {
    const indent = /^(\s+)"/m.exec(pkgSource)?.[1] ?? '  '
    writeFileSync(pkgPath, `${JSON.stringify({ ...pkg, scripts }, null, indent)}\n`)
    io.success(`package.json: added ${result.scripts.join(', ')}`)
  }

  const ignore = ['.open-next', '.dev.vars', '.wrangler'].filter(
    (path) => !isGitIgnored(root, path),
  )
  if (ignore.length > 0) {
    const gitignore = join(root, '.gitignore')
    const prefix =
      existsSync(gitignore) && !readFileSync(gitignore, 'utf8').endsWith('\n') ? '\n' : ''
    appendFileSync(
      gitignore,
      `${prefix}\n# Cloudflare (dopus)\n${ignore.map((p) => `${p}\n`).join('')}`,
    )
    io.success(`.gitignore: added ${ignore.join(', ')}`)
  }

  const deps: [string, string, boolean][] = [
    ['@opennextjs/cloudflare', '@opennextjs/cloudflare@^1', false],
    ['wrangler', 'wrangler@^4', true],
  ]
  for (const dev of [false, true]) {
    const missing = deps
      .filter(([n, , d]) => d === dev && !project.dependencies[n])
      .map(([, spec]) => spec)
    if (missing.length === 0) continue
    if (options.install === false) {
      io.warn(
        `Install yourself: ${project.packageManager} ${installArgs(project.packageManager, missing, dev).join(' ')}`,
      )
    } else if (
      await ask(
        `Install ${missing.join(', ')}${dev ? ' (dev)' : ''} with ${project.packageManager}?`,
        true,
      )
    ) {
      await io.install(project.packageManager, missing, root, dev)
      result.installed.push(...missing)
    }
  }

  const run = project.packageManager === 'npm' ? 'npm run' : project.packageManager
  io.note(
    [
      `Local Workers runtime:  ${run} cf:preview`,
      '  Wrangler reads .dev.vars (not .env.local): keep your key there too.',
      '',
      'Production secrets, once per Worker:',
      `  npx wrangler secret put ${keyEnv}`,
      `  npx wrangler secret put ${APPROVAL_SECRET_ENV}`,
      `Deploy:  ${run} cf:deploy`,
    ].join('\n'),
    'Deploy to Cloudflare Workers',
  )
  io.note(
    [
      'Duration: no wall-clock limit while the client is connected, and',
      '  waiting on the LLM is not CPU time. CPU limit: 30 s by default on',
      '  paid plans (limits.cpu_ms, max 5 min); the free plan allows 10 ms,',
      '  which a Next.js app usually exceeds.',
      'Keep-alive SSE comments (15 s) keep long tool calls open.',
      'Remove `export const runtime = "edge"`: OpenNext runs the Node runtime.',
    ].join('\n'),
    'Cloudflare notes',
  )
  return result
}
